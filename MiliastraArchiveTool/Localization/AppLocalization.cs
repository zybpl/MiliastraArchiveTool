    private string _currentLanguage = English;

    public IReadOnlyList<LanguageOption> Languages { get; } =
    [
        new(ChineseSimplified, "简体中文"),
        new(English, "English")
    ];

    public string CurrentLanguage
    {
        get => _currentLanguage;
        set
        {
            if (SetProperty(ref _currentLanguage, value))
                OnPropertyChanged("Item[]");
        }
    }

    public string this[string key] => Get(key);

    private string Get(string key)
    {
        if (Resources.TryGetValue(CurrentLanguage, out var active) &&
            active.TryGetValue(key, out var value))
            return value;

        if (Resources[ChineseSimplified].TryGetValue(key, out var fallback))
            return fallback;

        if (Resources[English].TryGetValue(key, out var englishFallback))
            return englishFallback;

        return key;
    }

